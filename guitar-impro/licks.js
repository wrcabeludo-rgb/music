  const DUR = { w: 4, h: 2, q: 1, e: 0.5, s: 0.25, t: 1 / 3 };

  function parse(tab) {
    const out = [];
    let t = 0;
    tab.split(/\s+/).filter(x => x && x !== '|').forEach(tok => {
      const m = tok.match(/^(r|\d:\d+(?:\+\d:\d+)*)([whqest])(\.?)(.*)$/);
      if (!m) throw new Error('Не понял токен: ' + tok);
      const d = DUR[m[2]] * (m[3] ? 1.5 : 1);
      const ev = { t, d };
      if (m[1] === 'r') ev.rest = true;
      else {
        ev.notes = m[1].split('+').map(p => { const [s, f] = p.split(':').map(Number); return { s, f, midi: TUN[s - 1] + f }; });
        const tech = m[4];
        const b = tech.match(/b(r?)(\d)/);
        if (b) { ev.bend = +b[2]; ev.release = !!b[1]; }
        ev.leg = tech.includes('h') ? 'h' : tech.includes('p') ? 'p' : tech.includes('s') ? 's' : null;
        if (tech.includes('~')) ev.vib = true;
      }
      out.push(ev);
      t += d;
    });
    return out;
  }

  // перенос в другую тональность сдвигом по грифу (без смены струн)
  function transpose(events, fromKey, toKey) {
    const delta = ((toKey - fromKey) % 12 + 12) % 12;
    const frets = events.filter(e => !e.rest).flatMap(e => e.notes.map(n => n.f));
    const lo = Math.min(...frets), hi = Math.max(...frets);
    const cands = [delta - 12, delta].filter(d => lo + d >= 0 && hi + d <= 20);
    cands.sort((a, b) => Math.abs(a) - Math.abs(b));
    const d = cands.length ? cands[0] : delta;
    return events.map(e => e.rest ? e : Object.assign({}, e, { notes: e.notes.map(n => ({ s: n.s, f: n.f + d, midi: n.midi + d })) }));
  }

