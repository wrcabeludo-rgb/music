// Фразы (лики) для импровизации и разбор табулатурной записи.
//
// Запись: «струна:лад» + длительность + приёмы, через пробел; «|» — тактовая черта.
//   длительности: w — целая, h — половинная, q — четверть, e — восьмая, s — шестнадцатая,
//                 t — триоль восьмыми; точка после буквы — с точкой (q. = 1,5 доли)
//   приёмы: b1/b2/b3 — подтяжка на 1–3 полутона, br2 — подтяжка и возврат,
//           h — хаммер, p — пулл-офф, s — слайд от предыдущей ноты, ~ — вибрато
//   двойные ноты: 3:7+2:5q ; пауза: rq, re, rh …
